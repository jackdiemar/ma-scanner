class SECMonitor:
    def __init__(self):
        self.session = requests.Session()
        self.session.headers.update({
            'User-Agent': 'Research research@example.com',
            'Host': 'www.sec.gov'
        })
        self.cik_cache = {}
        self.last_filings = {}  # Track what we've already seen
    
    def get_cik(self, ticker):
        if ticker in self.cik_cache:
            return self.cik_cache[ticker]
        try:
            url = "https://www.sec.gov/files/company_tickers.json"
            r = self.session.get(url, timeout=10)
            time.sleep(0.15)
            if r.status_code == 200:
                for entry in r.json().values():
                    if entry['ticker'].upper() == ticker.upper():
                        cik = str(entry['cik_str']).zfill(10)
                        self.cik_cache[ticker] = cik
                        return cik
        except:
            pass
        return None
    
    def check_new_filings(self, ticker):
        """Check for NEW Form 4 filings in last 24 hours"""
        cik = self.get_cik(ticker)
        if not cik:
            return None
        
        try:
            url = f"https://www.sec.gov/cgi-bin/browse-edgar?action=getcompany&CIK={cik}&type=4&dateb=&owner=include&count=10"
            r = self.session.get(url, timeout=10)
            time.sleep(0.2)
            
            soup = BeautifulSoup(r.content, 'html.parser')
            table = soup.find('table', {'class': 'tableFile2'})
            if not table:
                return None
            
            new_filings = []
            yesterday = datetime.now() - timedelta(days=1)
            
            for row in table.find_all('tr')[1:]:
                cols = row.find_all('td')
                if len(cols) < 5:
                    continue
                
                try:
                    date_str = cols[3].text.strip()
                    filing_date = datetime.strptime(date_str, '%Y-%m-%d')
                    
                    # Only check last 24 hours
                    if filing_date < yesterday:
                        break
                    
                    insider = cols[2].get_text(strip=True)
                    
                    # Check if C-level
                    if any(t in insider.lower() for t in ['ceo', 'cfo', 'coo', 'chief', 'president', 'director', 'officer']):
                        link = 'https://www.sec.gov' + cols[1].find('a')['href'] if cols[1].find('a') else ''
                        
                        # Create unique ID for this filing
                        filing_id = f"{ticker}_{date_str}_{insider[:20]}"
                        
                        # Only add if we haven't seen it before
                        if filing_id not in self.last_filings.get(ticker, set()):
                            new_filings.append({
                                'ticker': ticker,
                                'date': date_str,
                                'insider': insider,
                                'link': link,
                                'id': filing_id
                            })
                            
                            # Mark as seen
                            if ticker not in self.last_filings:
                                self.last_filings[ticker] = set()
                            self.last_filings[ticker].add(filing_id)
                
                except Exception as e:
                    continue
            
            return new_filings if new_filings else None
            
        except Exception as e:
            print(f"Error checking {ticker}: {e}")
            return None

