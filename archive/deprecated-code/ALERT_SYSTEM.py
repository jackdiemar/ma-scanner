    monitor = SECMonitor()
    urgent_alerts = []
    
    for ticker in WATCHLIST:
        try:
            new_filings = monitor.check_new_filings(ticker)
            
            if new_filings:
                print(f"🔥 {ticker}: {len(new_filings)} new Form 4(s)")
                
                # Calculate score
                score_data = quick_score(ticker)
                
                if score_data:
                    # Add SEC points
                    sec_score = score_data['score'] + (30 if len(new_filings) >= 3 else 25 if len(new_filings) >= 2 else 15)
                    
                    # URGENT if score 80+
                    if sec_score >= 80:
                        urgent_alerts.append({
                            'ticker': ticker,
                            'score': sec_score,
                            'filings': new_filings,
                            'signals': score_data['signals'],
                            'price': score_data['price']
                        })
        
        except Exception as e:
            pass
        
        time.sleep(0.5)
    
    # Send urgent alerts
    if urgent_alerts:
        send_urgent_alerts(urgent_alerts)
    
    print(f"✅ Check complete: {len(urgent_alerts)} urgent alerts")

