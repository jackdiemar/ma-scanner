def quick_score(ticker):
    """Quick score calculation for alerts"""
    try:
        import yfinance as yf
        
        stock = yf.Ticker(ticker)
        info = stock.info
        
        score = 0
        signals = []
        
        # Cash
        cash = info.get('totalCash', 0) or 0
        cf = info.get('operatingCashflow', 0) or 0
        if cf < 0 and cash > 0:
            burn = abs(cf) / 4
            if burn > 0:
                runway = cash / burn
                if runway < 2:
                    score += 25
                    signals.append(f"Critical Cash: {runway:.1f}Q")
                elif runway < 4:
                    score += 18
                    signals.append(f"Low Cash: {runway:.1f}Q")
        
        # Size
        mcap = info.get('marketCap', 0) or 0
        if 1e9 < mcap < 3e9:
            score += 15
            signals.append(f"Perfect Size: ${mcap/1e9:.1f}B")
        elif 500e6 < mcap < 5e9:
            score += 10
            signals.append(f"Good Size: ${mcap/1e9:.1f}B")
        
        # Valuation
        price = info.get('currentPrice', 0) or info.get('regularMarketPrice', 0)
        target = info.get('targetMeanPrice', 0) or 0
        if target > price > 0:
            upside = ((target - price) / price) * 100
            if upside > 50:
                score += 15
                signals.append(f"Undervalued: {upside:.0f}% upside")
        
        # Institutional
        inst = (info.get('heldPercentInstitutions', 0) or 0) * 100
        if inst > 85:
            score += 15
            signals.append(f"High Institutional: {inst:.0f}%")
        elif inst > 70:
            score += 12
            signals.append(f"Institutional: {inst:.0f}%")
        
        # Analysts
        analysts = info.get('numberOfAnalystOpinions', 0) or 0
        if analysts >= 10:
            score += 12
            signals.append(f"High Analyst Coverage: {analysts}")
        
        return {
            'score': score,
            'signals': signals,
            'price': price,
            'mcap': mcap
        }
    except:
        return None

